const pct = (n) => `${+n.toFixed(2)}%`;

function keyframes(name, f, slots) {
  const ev = [];
  const has0 = slots.some(([a]) => a === 0);
  if (!has0) ev.push([0, 0]);
  for (const [a, b] of slots) { ev.push([a, 1]); if (b < 100) ev.push([b, 0]); }
  ev.sort((x, y) => x[0] - y[0]);
  return `@keyframes ${name}-${f} { ${ev.map(([t, v]) => `${pct(t)} { opacity: ${v}; }`).join(' ')} }`;
}

function block() {
  const out = [];
  out.push('/* BEGIN stitched frames: generated by tools/stitch/css.js from its table of slots. Change the table, not the numbers. */');
  for (const s of SETS) {
    for (const f of Object.keys(s.slots)) out.push(`.scene .anim-${s.name}-${f} { animation: ${s.name}-${f} var(${s.loop}) step-end infinite; animation-delay: var(--phase, 0s); }`);
    for (const f of Object.keys(s.slots)) out.push(keyframes(s.name, f, s.slots[f]));
  }
  out.push('/* END stitched frames */');
  return out.join('\n');
}

if (require.main === module) {
  const text = block();
  if (process.argv.includes('--write')) {
    const file = path.join(__dirname, '..', '..', 'dashboard', 'public', 'app.css');
    const css = fs.readFileSync(file, 'utf8');
    const a = css.indexOf('/* BEGIN stitched frames');
    const b = css.indexOf('/* END stitched frames */');
    if (a < 0 || b < 0) throw new Error('markers not found in app.css');
    fs.writeFileSync(file, css.slice(0, a) + text + css.slice(b + '/* END stitched frames */'.length));
    console.log(`wrote ${SETS.length} frame sets into app.css`);
  } else console.log(text);
}

module.exports = { SETS, block };
